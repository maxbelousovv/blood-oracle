#!/usr/bin/env node
/**
 * Reads the coterie type table (xlsx) and writes two things:
 *
 *   node tools/extract-coterie-types.mjs <table.xlsx> <texts.json> [catalogue.js]
 *
 * 1. texts.json — the types' descriptions. Rulebook text, so it is private:
 *    blood-oracle-coterie.json next to the rules reference in Foundry's Data
 *    directory, never in the repository.
 * 2. catalogue.js (optional) — names, domain ratings, grants, choices and
 *    possible extras: the mechanics, which ship with the module. Regenerate it
 *    into src/app/rules/coterie-types.js when the table changes.
 *
 * Columns of the first sheet: type, description, Chasse, Lien, Portillon,
 * backgrounds, flaws, choices, possible extras. The table's second sheet
 * explains the formats.
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { readZip, readFirstSheet } from './xlsx.mjs'

const [, , tablePath, textsPath, cataloguePath] = process.argv

if (!tablePath || !textsPath) {
  console.error('Usage: node tools/extract-coterie-types.mjs <table.xlsx> <texts.json> [catalogue.js]')
  process.exit(1)
}

const slug = (text) =>
  String(text)
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')

const problems = []

/**
 * "Mawla 3 (whoever tasks you)" → { name: 'Mawla', dots: 3, detail: 'whoever tasks you' }
 * "Status: Suspect 1"           → { name: 'Suspect', of: 'Status', dots: 1 }
 */
function parseGrant(text, where) {
  const match = String(text).trim().match(/^(.+?)\s+(\d+)\s*(?:\((.*)\))?\s*$/)
  if (!match) {
    problems.push(`${where}: could not read "${text}"`)
    return null
  }
  const [, rawName, dots, detail] = match
  const [of, name] = rawName.includes(':') ? rawName.split(':').map((part) => part.trim()) : [null, rawName.trim()]
  return { name, dots: Number(dots), ...(detail ? { detail: detail.trim() } : {}), ...(of ? { of } : {}) }
}

const list = (cell) =>
  String(cell ?? '')
    .split(';')
    .map((part) => part.trim())
    .filter(Boolean)

function parseChoices(cell, where) {
  const text = String(cell ?? '').trim()
  if (!text) return []
  if (/^one of:/i.test(text)) {
    const options = text
      .replace(/^one of:/i, '')
      .split('|')
      .map((part) => parseGrant(part, where))
      .filter(Boolean)
    return [{ kind: 'oneOf', options }]
  }
  return text
    .split('|')
    .map((block) => block.trim())
    .filter(Boolean)
    .map((block) => {
      const spread = block.match(/^spread\s+(\d+):\s*(.+)$/i)
      if (spread) {
        return {
          kind: 'spread',
          total: Number(spread[1]),
          among: spread[2].split(',').map((name) => name.trim()).filter(Boolean)
        }
      }
      if (/^flaws:\s*equal$/i.test(block)) return { kind: 'flawsEqual' }
      problems.push(`${where}: choice not understood — "${block}"`)
      return null
    })
    .filter(Boolean)
}

const rating = (cell) => {
  const value = Number(String(cell ?? '').trim())
  return Number.isFinite(value) && value > 0 ? value : 0
}

const [, ...rows] = readFirstSheet(readZip(readFileSync(tablePath)))
const catalogue = []
const texts = {}

for (const row of rows) {
  const name = String(row[0] ?? '').trim()
  if (!name) continue
  const id = slug(name)

  catalogue.push({
    id,
    name,
    domain: { chasse: rating(row[2]), lien: rating(row[3]), portillon: rating(row[4]) },
    backgrounds: list(row[5]).map((part) => parseGrant(part, name)).filter(Boolean),
    flaws: list(row[6]).map((part) => parseGrant(part, name)).filter(Boolean),
    choices: parseChoices(row[7], name),
    extras: list(row[8])
  })
  texts[id] = { description: String(row[1] ?? '').trim() }
}

// The coterie merits and flaws write to the same file; keep theirs.
let file = { format: 'blood-oracle-coterie', version: 1 }
if (existsSync(textsPath)) {
  try {
    const current = JSON.parse(readFileSync(textsPath, 'utf8'))
    if (current?.format === 'blood-oracle-coterie') file = current
  } catch {
    problems.push(`${textsPath} could not be read; writing a fresh one`)
  }
}
file.generated = new Date().toISOString()
file.types = texts
writeFileSync(textsPath, JSON.stringify(file))
console.log(`Wrote ${textsPath}: ${Object.keys(texts).length} coterie types (merits and flaws kept: ${Object.keys(file.advantages ?? {}).length})`)

if (cataloguePath) {
  writeFileSync(
    cataloguePath,
    '// Generated by tools/extract-coterie-types.mjs — do not edit by hand.\n' +
      '// Mechanics only; the descriptions live in the private\n' +
      '// blood-oracle-coterie.json next to the rules reference.\n\n' +
      `export const COTERIE_TYPES = ${JSON.stringify(catalogue, null, 2)}\n`
  )
  console.log(`Wrote ${cataloguePath}: ${catalogue.length} coterie types`)
}

if (problems.length) {
  console.log(`\n${problems.length} things to look at:`)
  for (const problem of problems) console.log(`  - ${problem}`)
}
