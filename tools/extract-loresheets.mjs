#!/usr/bin/env node
/**
 * Reads the loresheet table (xlsx) and writes two things:
 *
 *   node tools/extract-loresheets.mjs <table.xlsx> <texts.json> [catalogue.js]
 *
 * 1. texts.json — descriptions and level texts. Close to rulebook text, so it
 *    is private, like the rules reference: it goes next to that file in
 *    Foundry's Data directory and never into the repository.
 * 2. catalogue.js (optional) — names, level names and who may take each
 *    loresheet. No rules text, so it ships with the module; regenerate it into
 *    src/app/rules/loresheets.js when the table gains loresheets.
 *
 * Expected columns, in order: name, description, the five levels as
 * "Level name: text", and a comment holding the restriction in brackets,
 * e.g. "(Ventrue characters only)".
 *
 * No dependencies: see tools/xlsx.mjs.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { readZip, readFirstSheet } from './xlsx.mjs'

const [, , tablePath, textsPath, cataloguePath] = process.argv

if (!tablePath || !textsPath) {
  console.error('Usage: node tools/extract-loresheets.mjs <table.xlsx> <texts.json> [catalogue.js]')
  process.exit(1)
}

/* ---------------------------------------------------------- loresheets */

const slug = (text) =>
  String(text)
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')

// The names clans go by in a restriction, and how the sheet's clan reads them.
const CLANS = [
  ['banu haqim', 'banu haqim'],
  ['ministry', 'ministry'],
  ['ventrue', 'ventrue'],
  ['toreador', 'toreador'],
  ['brujah', 'brujah'],
  ['nosferatu', 'nosferatu'],
  ['malkavian', 'malkavian'],
  ['tremere', 'tremere'],
  ['gangrel', 'gangrel'],
  ['lasombra', 'lasombra'],
  ['hecata', 'hecata'],
  ['tzimisce', 'tzimisce'],
  ['ravnos', 'ravnos'],
  ['salubri', 'salubri']
]

/**
 * "(Ventrue characters only)" → { clans: ['ventrue'] }
 * "(Unavailable to Nosferatu characters)" → { notClans: ['nosferatu'] }
 * "(Blood Sorcery Users Only)" → { discipline: 'sorcery' }
 * "(Thin-Blood Alchemists Only)" → { clans: ['thin'], discipline: 'alchemy' }
 */
function parseRestriction(comment) {
  const text = String(comment ?? '').trim()
  if (!text) return null
  const inner = (text.match(/\(([^)]*)\)/)?.[1] ?? text).trim()
  const lower = inner.toLowerCase()
  const restriction = { text: inner }

  if (/blood sorcery/.test(lower)) restriction.discipline = 'sorcery'
  if (/thin-?blood/.test(lower)) {
    restriction.clans = ['thin']
    if (/alchemist/.test(lower)) restriction.discipline = 'alchemy'
  }

  const named = CLANS.filter(([word]) => lower.includes(word)).map(([, key]) => key)
  if (named.length) {
    if (/unavailable|not available|except/.test(lower)) restriction.notClans = named
    else restriction.clans = [...new Set([...(restriction.clans ?? []), ...named])]
  }

  if (!restriction.clans && !restriction.notClans && !restriction.discipline) restriction.unparsed = true
  return restriction
}

function splitLevel(cell) {
  const text = String(cell ?? '').trim()
  const colon = text.indexOf(':')
  // A name is short; a colon far into the text belongs to the text.
  if (colon > 0 && colon <= 80) {
    return { name: text.slice(0, colon).trim(), text: text.slice(colon + 1).trim() }
  }
  return { name: text.split(/[.!?]/)[0].slice(0, 60).trim(), text }
}

const file = readZip(readFileSync(tablePath))
const [, ...rows] = readFirstSheet(file)

const catalogue = []
const texts = {}
const seen = new Set()
const problems = []

for (const row of rows) {
  const name = String(row[0] ?? '').trim()
  if (!name) continue

  let id = slug(name)
  while (seen.has(id)) id += '-2'
  seen.add(id)

  const levels = [2, 3, 4, 5, 6].map((column) => splitLevel(row[column]))
  if (levels.some((level) => !level.name)) problems.push(`${name}: a level is empty`)

  const restriction = parseRestriction(row[7])
  if (restriction?.unparsed) problems.push(`${name}: restriction not understood — "${restriction.text}"`)

  catalogue.push({
    id,
    name,
    levels: levels.map((level) => level.name),
    ...(restriction ? { restriction } : {})
  })
  texts[id] = {
    description: String(row[1] ?? '').trim(),
    levels: levels.map((level) => level.text)
  }
}

writeFileSync(
  textsPath,
  JSON.stringify({
    format: 'blood-oracle-loresheets',
    version: 1,
    generated: new Date().toISOString(),
    loresheets: texts
  })
)
console.log(`Wrote ${textsPath}: ${Object.keys(texts).length} loresheets with texts`)

if (cataloguePath) {
  const body =
    '// Generated by tools/extract-loresheets.mjs — do not edit by hand.\n' +
    '// Names and restrictions only; the rules text lives in the private\n' +
    '// blood-oracle-loresheets.json next to the rules reference.\n\n' +
    `export const LORESHEETS = ${JSON.stringify(catalogue, null, 2)}\n`
  writeFileSync(cataloguePath, body)
  console.log(`Wrote ${cataloguePath}: ${catalogue.length} loresheets`)
}

if (problems.length) {
  console.log(`\n${problems.length} things to look at:`)
  for (const problem of problems) console.log(`  - ${problem}`)
}
